def compile_all(check_only: bool = False) -> dict[Path, str]:
    """Compile all semantic targets and write to disk (or check for zero drift)."""
    spec = load_semantic_spec()
    qs_dataset, qs_dashboard = compile_quicksight_specs(spec)

    artifacts: dict[Path, str] = {
        ROOT_DIR / "redshift" / "sql" / "05_governed_semantic_views.sql": compile_redshift_semantic_sql(spec),
        ROOT_DIR / "databricks" / "sql" / "unity_catalog_metric_views.sql": compile_unity_catalog_metric_view(spec),
        ROOT_DIR / "bi" / "powerbi" / "evm_measures.dax": compile_powerbi_dax(spec),
        ROOT_DIR / "bi" / "powerbi" / "EVM_Semantic_Model.bim": compile_powerbi_bim(spec),
        ROOT_DIR / "bi" / "powerbi" / "redshift_composite_directquery.pq": compile_powerbi_m_script(),
        ROOT_DIR / "bi" / "quicksight" / "dataset_spice_directquery_rls.json": qs_dataset,
        ROOT_DIR / "bi" / "quicksight" / "dashboard_4_sheet_definition.json": qs_dashboard,
    }

    drifted: list[str] = []
    for path, content in artifacts.items():
        if check_only:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                drifted.append(str(path.relative_to(ROOT_DIR)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")

    if check_only and drifted:
        raise RuntimeError(f"Semantic artifacts out of sync with TOML spec: {drifted}")

    return artifacts


def main() -> None:
    parser = argparse.ArgumentParser(description="Compile Governed Semantic Layer artifacts.")
    parser.add_argument("--check", action="store_true", help="Verify zero drift without writing.")
    args = parser.parse_args()
    try:
        outputs = compile_all(check_only=args.check)
    except Exception as exc:
        print(f"[ERROR] {exc}", file=sys.stderr)
        sys.exit(1)
    mode = "Verified zero drift across" if args.check else "Compiled"
    print(f"[OK] {mode} {len(outputs)} governed semantic artifacts from evm_semantic_model.toml")


if __name__ == "__main__":
    main()
