#!/usr/bin/env python3
"""Zero-dbt Governed Semantic Layer Compiler.

Reads `semantic/evm_semantic_model.toml` once and deterministically compiles:
  1. Amazon Redshift Governed Semantic Views & Native RLS Policy SQL
  2. Databricks Unity Catalog Metric Views DDL (`WITH METRICS LANGUAGE YAML`)
  3. Power BI Tabular Model (`EVM_Semantic_Model.bim`), DAX (`evm_measures.dax`), & DirectQuery M
  4. Amazon QuickSight SPICE + DirectQuery RLS Dataset & 4-Sheet Dashboard JSON specs
"""

from __future__ import annotations

import argparse
import json
import sys
import tomllib
from pathlib import Path
from typing import Any

ROOT_DIR = Path(__file__).resolve().parent.parent
SPEC_PATH = ROOT_DIR / "semantic" / "evm_semantic_model.toml"


def load_semantic_spec(spec_path: Path = SPEC_PATH) -> dict[str, Any]:
    """Load and validate the canonical TOML semantic model."""
    with spec_path.open("rb") as fh:
        spec = tomllib.load(fh)
    required_sections = {"model", "dimensions", "base_measures", "derived_metrics", "rls_personas"}
    missing = required_sections - set(spec.keys())
    if missing:
        raise ValueError(f"Semantic model missing required sections: {sorted(missing)}")
    return spec


def compile_redshift_semantic_sql(spec: dict[str, Any]) -> str:
    """Compile Amazon Redshift Governed Semantic Views & Native RLS Policies."""
    base_cols = ",\n    ".join(
        f"{m['aggregation']}(f.{m['column']}) AS {m['name']}" for m in spec["base_measures"]
    )
    evm_derived = [
        m for m in spec["derived_metrics"] if m["category"] != "Workforce Capacity"
    ]
    derived_cols = ",\n    ".join(
        f"{m['sql_expr']} AS {m['name']}" for m in evm_derived
    )

    rls_cases = []
    for persona in spec["rls_personas"]:
        regions_sql = ", ".join(f"'{r}'" for r in persona["allowed_regions"])
        rls_cases.append(
            f"-- Persona {persona['role']}: {persona['description']}\n"
            f"CREATE RLS POLICY rls_{persona['role'].lower()} WITH (region_code VARCHAR(16))\n"
            f"USING (region_code IN ({regions_sql}));"
        )
    rls_block = "\n\n".join(rls_cases)

    return f"""-- =============================================================================
-- AUTO-GENERATED BY src/semantic_compiler.py FROM semantic/evm_semantic_model.toml
-- DO NOT EDIT MANUALLY — ZERO-DRIFT GOVERNED REDSHIFT SEMANTIC & RLS LAYER
-- =============================================================================

-- 1. Row-Grain Portfolio Enriched Semantic View (for QuickSight SPICE & Power BI DirectQuery)
CREATE OR REPLACE VIEW gold.v_semantic_evm_portfolio AS
SELECT
    f.snapshot_date,
    d.fiscal_year,
    d.fiscal_quarter,
    d.month_name,
    f.project_sk,
    p.project_id,
    p.project_name,
    f.region_code,
    r.region_name,
    r.maturity_stage,
    p.practice_area,
    p.contract_type,
    p.project_manager,
    f.bac_usd,
    f.cum_pv_usd,
    f.cum_ev_usd,
    f.cum_ac_labor_usd,
    f.cum_ac_cloud_usd,
    f.cum_ac_total_usd,
    f.pct_complete
FROM {spec['model']['fact_table_redshift']} f
INNER JOIN gold.dim_project p ON f.project_sk = p.project_sk
INNER JOIN gold.dim_region r  ON f.region_code = r.region_code
INNER JOIN gold.dim_date d    ON f.snapshot_date = d.snapshot_date;

-- 2. Executive Pre-Weighted Semantic Rollup View (Prevents Naive AVG(CPI) Across Projects!)
CREATE OR REPLACE VIEW gold.v_semantic_evm_executive_kpis AS
SELECT
    f.snapshot_date,
    f.region_code,
    p.practice_area,
    {base_cols},
    {derived_cols}
FROM {spec['model']['fact_table_redshift']} f
INNER JOIN gold.dim_project p ON f.project_sk = p.project_sk
GROUP BY f.snapshot_date, f.region_code, p.practice_area;

-- 3. Native Amazon Redshift Row-Level Security (RLS) Policies
{rls_block}

-- Attach RLS to fact tables and turn enforcement ON:
-- ATTACH RLS POLICY rls_vp_mena ON gold.fact_evm_daily TO ROLE role_vp_mena;
-- ALTER TABLE gold.fact_evm_daily ROW LEVEL SECURITY ON;
"""


def compile_unity_catalog_metric_view(spec: dict[str, Any]) -> str:
    """Compile Databricks Unity Catalog Metric View DDL (Zero-dbt Native Metric Layer)."""
    measures_yaml = []
    for m in spec["base_measures"]:
        measures_yaml.append(
            f"  - name: {m['name']}\n    expr: {m['aggregation']}({m['column']})"
        )
    for m in spec["derived_metrics"]:
        if m["category"] != "Workforce Capacity":
            clean_expr = m["sql_expr"].replace("f.", "")
            measures_yaml.append(f"  - name: {m['name']}\n    expr: {clean_expr}")

    measures_str = "\n".join(measures_yaml)
    return f"""-- =============================================================================
-- AUTO-GENERATED BY src/semantic_compiler.py FROM semantic/evm_semantic_model.toml
-- Databricks Unity Catalog Governed Metric View + Row Filter Security
-- =============================================================================

CREATE OR REPLACE FUNCTION evm_enterprise_prod.gold.fn_rls_region_filter(region_param STRING)
RETURN
    IS_ACCOUNT_GROUP_MEMBER('GLOBAL_CFO')
    OR (IS_ACCOUNT_GROUP_MEMBER('VP_MENA') AND region_param = 'MENA')
    OR (IS_ACCOUNT_GROUP_MEMBER('VP_EMEA') AND region_param = 'EMEA')
    OR (IS_ACCOUNT_GROUP_MEMBER('VP_AMER') AND region_param = 'AMER')
    OR (IS_ACCOUNT_GROUP_MEMBER('VP_APAC') AND region_param = 'APAC');

ALTER TABLE {spec['model']['fact_table_databricks']}
SET ROW FILTER evm_enterprise_prod.gold.fn_rls_region_filter ON (region_code);

CREATE OR REPLACE VIEW evm_enterprise_prod.gold.mv_evm_executive_metrics
WITH METRICS
LANGUAGE YAML
AS $$
version: 0.1
source: {spec['model']['fact_table_databricks']}
dimensions:
  - name: snapshot_date
    expr: snapshot_date
  - name: region_code
    expr: region_code
  - name: project_sk
    expr: project_sk
measures:
{measures_str}
$$;
"""


def compile_powerbi_dax(spec: dict[str, Any]) -> str:
    """Compile production Power BI DAX measures preventing ratio aggregation errors."""
    blocks = [
        "// =============================================================================",
        "// AUTO-GENERATED BY src/semantic_compiler.py FROM semantic/evm_semantic_model.toml",
        "// Power BI Enterprise Semantic Measures (Composite Mode: Redshift DirectQuery)",
        "// =============================================================================",
        "",
    ]
    for m in spec["base_measures"]:
        blocks.append(f"// {m['description']}")
        blocks.append(
            f"{m['label']} = {m['aggregation']}('fact_evm_daily'[{m['column']}])\n"
        )
    for m in spec["derived_metrics"]:
        blocks.append(f"// [{m['category']}] {m['description']}")
        blocks.append(f"{m['label']} = {m['dax_expr']}\n")

    # Add Executive S-Curve & Quadrant Classification DAX helpers
    blocks.append(
        "// [Executive Matrix] 4-Quadrant Portfolio Risk Classification\n"
        "EVM Health Quadrant = \n"
        "VAR _cpi = [Cost Performance Index (CPI)]\n"
        "VAR _spi = [Schedule Performance Index (SPI)]\n"
        "RETURN\n"
        "SWITCH(\n"
        "    TRUE(),\n"
        "    ISBLANK(_cpi) || ISBLANK(_spi), \"UNSTARTED\",\n"
        "    _cpi >= 1.0 && _spi >= 1.0, \"Q1: Optimal (Under Budget & Ahead)\",\n"
        "    _cpi >= 0.92 && _spi >= 0.92, \"Q2: Healthy Watchlist\",\n"
        "    _cpi < 0.92 && _spi >= 0.92, \"Q3: Cost Overrun Risk\",\n"
        "    _cpi >= 0.92 && _spi < 0.92, \"Q4: Schedule Slippage\",\n"
        "    \"CRITICAL: Dual Cost & Schedule Breach\"\n"
        ")\n"
    )
    return "\n".join(blocks)


